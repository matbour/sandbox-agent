#!/bin/sh
# Check that commit messages follow Conventional Commits (https://www.conventionalcommits.org):
#
#   <type>[(<scope>)][!]: <description>
#
# with a type from TYPES, a lowercase scope, a description that starts with a lowercase letter and
# does not end with a period, and a subject of at most 72 characters.
#
#   check-commit-messages.sh <message file>   commit-msg hook: the message being written
#   check-commit-messages.sh --pre-push       pre-push hook: every commit about to be pushed,
#                                             read from the refs Git passes on stdin
#   check-commit-messages.sh <revision range> any range, e.g. origin/main..HEAD
#
# Both hooks are in lefthook.yml. Merge commits generated by Git are allowed; fixup! and squash!
# commits are allowed locally but refused on push.
set -eu

TYPES='build|chore|ci|docs|feat|fix|perf|refactor|revert|style|test'
PATTERN="^($TYPES)(\([a-z0-9][a-z0-9._/-]*\))?!?: [a-z0-9\`(].*[^.]\$"
MAX=72
ZERO=0000000000000000000000000000000000000000

failed=0

# check SUBJECT WHERE MODE: MODE is "local" (commit-msg) or "push".
check() {
	subject=$1 where=$2 mode=$3
	case $subject in
	"Merge "*) return 0 ;;
	"fixup! "* | "squash! "* | "amend! "*)
		[ "$mode" = local ] && return 0
		echo "$where: \"$subject\": squash it before pushing" >&2
		failed=1
		return 0
		;;
	esac
	if ! printf '%s\n' "$subject" | grep -Eq "$PATTERN"; then
		echo "$where: \"$subject\" is not a Conventional Commit" >&2
		failed=1
	elif [ "${#subject}" -gt "$MAX" ]; then
		echo "$where: \"$subject\" is ${#subject} characters, more than $MAX" >&2
		failed=1
	fi
}

check_range() {
	for c in $(git rev-list "$@"); do
		check "$(git log -1 --format=%s "$c")" "$(git rev-parse --short "$c")" push
	done
}

case ${1:-} in
"")
	echo "usage: $0 <message file> | --pre-push | <revision range>" >&2
	exit 2
	;;
--pre-push)
	while read -r _ local_sha _ remote_sha; do
		[ "$local_sha" = "$ZERO" ] && continue # deleting a branch
		if [ "$remote_sha" != "$ZERO" ] && git cat-file -e "$remote_sha^{commit}" 2>/dev/null; then
			check_range "$remote_sha..$local_sha"
		else # new branch, or a remote commit we do not have (force push): what no remote has yet
			check_range "$local_sha" --not --remotes
		fi
	done
	;;
*)
	if [ -f "$1" ]; then
		# The first line that is neither a comment nor blank, as Git would keep it.
		subject=$(grep -v '^#' "$1" | sed '/^[[:space:]]*$/d' | head -n 1)
		check "$subject" "commit message" local
	else
		check_range "$@"
	fi
	;;
esac

if [ "$failed" -ne 0 ]; then
	echo "Expected <type>[(scope)][!]: <description>, with type one of: $TYPES" | sed 's/|/, /g' >&2
	exit 1
fi
