#!/bin/sh
# Check that commit messages follow Conventional Commits (https://www.conventionalcommits.org).
# The rules are in .commitlint.yaml and checked by commitlint
# (github.com/conventionalcommit/commitlint); this script only decides which commits to check.
# The commit-msg hook calls commitlint directly (lefthook.yml).
#
#   check-commit-messages.sh --pre-push       pre-push hook: every commit about to be pushed,
#                                             read from the refs Git passes on stdin
#   check-commit-messages.sh <revision range> any range, e.g. origin/main..HEAD
#
# Merge commits generated by Git are allowed; fixup!, squash! and amend! commits are refused.
set -eu

# Same version as the commitlint template in lefthook.yml: change both.
GO=${GO:-$(command -v go 2>/dev/null || echo "$HOME/.local/go/bin/go")}
COMMITLINT="$GO run github.com/conventionalcommit/commitlint@v0.12.0"
ZERO=0000000000000000000000000000000000000000

failed=0

check_range() {
	for c in $(git rev-list "$@"); do
		short=$(git rev-parse --short "$c")
		subject=$(git log -1 --format=%s "$c")

		case $subject in
		"fixup! "* | "squash! "* | "amend! "*)
			echo "$short: \"$subject\": squash it before pushing" >&2
			failed=1
			continue
			;;
		esac

		if ! report=$(git log -1 --format=%B "$c" | $COMMITLINT lint 2>&1); then
			printf '%s: "%s"\n%s\n' "$short" "$subject" "$report" >&2
			failed=1
		fi
	done
}

case ${1:-} in
"")
	echo "usage: $0 --pre-push | <revision range>" >&2
	exit 2
	;;
--pre-push)
	while read -r _ local_sha _ remote_sha; do
		[ "$local_sha" = "$ZERO" ] && continue # deleting a branch

		if [ "$remote_sha" != "$ZERO" ] && git cat-file -e "$remote_sha^{commit}" 2>/dev/null; then
			check_range "$remote_sha..$local_sha"
		else # new branch, or a remote commit we do not have (force push): what no remote has yet
			check_range "$local_sha" --not --remotes
		fi
	done
	;;
*)
	check_range "$@"
	;;
esac

exit "$failed"
