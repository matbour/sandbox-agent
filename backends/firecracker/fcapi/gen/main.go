// Command gen writes Go types for the definitions of Firecracker's OpenAPI (Swagger 2.0)
// specification. The specification only uses objects, strings, integers, booleans, arrays,
// references and enums, so a small generator does the job without the dependencies, and the
// failures on this file, of a general one (D54).
//
//	go run ./gen <firecracker.yaml> <types.go>
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"unicode"

	"gopkg.in/yaml.v3"
)

// schema is the part of a Swagger schema the specification uses. Properties keep their order
// from the file, so the structs read like the specification.
type schema struct {
	Type                 string   `yaml:"type"`
	Format               string   `yaml:"format"`
	Description          string   `yaml:"description"`
	Ref                  string   `yaml:"$ref"`
	Enum                 []string `yaml:"enum"`
	Required             []string `yaml:"required"`
	Items                *schema  `yaml:"items"`
	Properties           ordered  `yaml:"properties"`
	AdditionalProperties any      `yaml:"additionalProperties"`
}

type ordered struct {
	names  []string
	byName map[string]*schema
}

func (o *ordered) UnmarshalYAML(n *yaml.Node) error {
	o.byName = map[string]*schema{}

	for i := 0; i+1 < len(n.Content); i += 2 {
		var s schema
		if err := n.Content[i+1].Decode(&s); err != nil {
			return err
		}

		name := n.Content[i].Value
		o.names = append(o.names, name)
		o.byName[name] = &s
	}

	return nil
}

type spec struct {
	Info struct {
		Version string `yaml:"version"`
	} `yaml:"info"`
	Definitions ordered `yaml:"definitions"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen <firecracker.yaml> <types.go>")
		os.Exit(2)
	}

	b, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}

	var s spec
	if err := yaml.Unmarshal(b, &s); err != nil {
		fail(err)
	}

	code, err := generate(s)
	if err != nil {
		fail(err)
	}

	if err := os.WriteFile(os.Args[2], code, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}

// generator collects the named enum types found inside structs while writing them.
type generator struct {
	out   bytes.Buffer
	enums []enum
}

type enum struct {
	name, doc string
	values    []string
}

func generate(s spec) ([]byte, error) {
	g := &generator{}

	fmt.Fprintf(&g.out, "// Code generated by fcapi/gen from Firecracker's OpenAPI specification %s. DO NOT EDIT.\n\n", s.Info.Version)
	fmt.Fprintf(&g.out, "package fcapi\n\n")
	fmt.Fprintf(&g.out, "// Version is the Firecracker API version these types describe.\nconst Version = %q\n\n", s.Info.Version)

	names := append([]string(nil), s.Definitions.names...)
	sort.Strings(names)

	for _, name := range names {
		if err := g.definition(name, s.Definitions.byName[name]); err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
	}

	for _, e := range g.enums {
		g.writeEnum(e)
	}

	return format.Source(g.out.Bytes())
}

func (g *generator) definition(name string, d *schema) error {
	switch {
	case d.Type == "object" && len(d.Properties.names) > 0:
		g.comment(name, d.Description, "")
		fmt.Fprintf(&g.out, "type %s struct {\n", name)

		required := map[string]bool{}
		for _, r := range d.Required {
			required[r] = true
		}

		for _, p := range d.Properties.names {
			ps := d.Properties.byName[p]
			field := goName(p)

			t, err := g.goType(name+field, ps)
			if err != nil {
				return fmt.Errorf("%s: %w", p, err)
			}

			tag := p
			if !required[p] {
				tag += ",omitempty"
				if !strings.HasPrefix(t, "[]") && !strings.HasPrefix(t, "map[") {
					t = "*" + t
				}
			}

			g.comment(field, ps.Description, "\t")
			fmt.Fprintf(&g.out, "\t%s %s `json:%q`\n", field, t, tag)
		}

		fmt.Fprintf(&g.out, "}\n\n")
	case d.Type == "object":
		g.comment(name, d.Description, "")
		fmt.Fprintf(&g.out, "type %s map[string]any\n\n", name)
	case d.Type == "string" && len(d.Enum) > 0:
		g.enums = append(g.enums, enum{name: name, doc: d.Description, values: d.Enum})
	default:
		t, err := g.goType(name, d)
		if err != nil {
			return err
		}

		g.comment(name, d.Description, "")
		fmt.Fprintf(&g.out, "type %s %s\n\n", name, t)
	}

	return nil
}

// goType is the Go type of a schema; an inline string enum becomes a named type called hint.
func (g *generator) goType(hint string, s *schema) (string, error) {
	if s.Ref != "" {
		return strings.TrimPrefix(s.Ref, "#/definitions/"), nil
	}

	switch s.Type {
	case "string":
		if len(s.Enum) > 0 {
			g.enums = append(g.enums, enum{name: hint, doc: s.Description, values: s.Enum})

			return hint, nil
		}

		return "string", nil
	case "integer":
		return "int64", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "array":
		if s.Items == nil {
			return "", fmt.Errorf("array without items")
		}

		t, err := g.goType(hint+"Item", s.Items)
		if err != nil {
			return "", err
		}

		return "[]" + t, nil
	case "object":
		return "map[string]any", nil
	}

	return "", fmt.Errorf("unsupported type %q", s.Type)
}

func (g *generator) writeEnum(e enum) {
	g.comment(e.name, e.doc, "")
	fmt.Fprintf(&g.out, "type %s string\n\n", e.name)
	fmt.Fprintf(&g.out, "// Values of %s.\nconst (\n", e.name)

	for _, v := range e.values {
		fmt.Fprintf(&g.out, "\t%s%s %s = %q\n", e.name, goName(v), e.name, v)
	}

	fmt.Fprintf(&g.out, ")\n\n")
}

// comment writes a Go doc comment starting with the identifier, wrapped at 100 columns.
func (g *generator) comment(ident, text, indent string) {
	text = strings.Join(strings.Fields(text), " ")
	if text == "" {
		return
	}

	line := indent + "//"
	for _, w := range strings.Fields(ident + " " + lowerFirst(text)) {
		if len(line)+1+len(w) > 100 && line != indent+"//" {
			g.out.WriteString(line + "\n")
			line = indent + "//"
		}

		line += " " + w
	}

	g.out.WriteString(line + "\n")
}

func lowerFirst(s string) string {
	r := []rune(s)
	if len(r) > 1 && unicode.IsUpper(r[0]) && !unicode.IsUpper(r[1]) {
		r[0] = unicode.ToLower(r[0])
	}

	return string(r)
}

// goName turns snake_case, kebab-case and values like "2M" into an exported Go name, keeping
// Go's initialisms.
func goName(s string) string {
	var b strings.Builder

	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == ' ' || r == '.' }) {
		if up, ok := initialisms[strings.ToLower(part)]; ok {
			b.WriteString(up)

			continue
		}

		r := []rune(part)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}

	name := b.String()
	if name == "" || unicode.IsDigit([]rune(name)[0]) {
		name = "V" + name
	}

	return name
}

var initialisms = map[string]string{
	"id": "ID", "uds": "UDS", "mac": "MAC", "ip": "IP", "ipv4": "IPv4", "cpu": "CPU", "vcpu": "VCPU",
	"mmds": "MMDS", "mib": "MiB", "uffd": "UFFD", "url": "URL", "api": "API", "smt": "SMT",
	"oom": "OOM", "cid": "CID", "msr": "MSR", "kvm": "KVM", "numa": "NUMA", "mtu": "MTU", "uuid": "UUID",
	"partuuid": "PartUUID", "imds": "IMDS", "dmb": "DMB", "vm": "VM", "vmm": "VMM", "io": "IO",
}
